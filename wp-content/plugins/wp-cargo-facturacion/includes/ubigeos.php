/**
 * Obtiene los departamentos únicos de la BD
 * @return array Array de departamentos
 */
function wpcfact_get_departamentos() {
	global $wpdb;
	$table = $wpdb->prefix . 'ubigeos';
	$results = $wpdb->get_results(
		"SELECT DISTINCT departamento, nombre FROM `{$table}` 
		WHERE provincia = '00' AND distrito = '00'
		ORDER BY departamento ASC"
	);
	$departamentos = array();
	foreach ( $results as $row ) {
		$departamentos[ $row->departamento ] = $row->nombre;
	}
	return $departamentos;
}

/**
 * Obtiene las provincias de un departamento
 * @param string $departamento Código de departamento
 * @return array Array de provincias
 */
function wpcfact_get_provincias( $departamento ) {
	global $wpdb;
	$table = $wpdb->prefix . 'ubigeos';
	$results = $wpdb->get_results( $wpdb->prepare(
		"SELECT DISTINCT provincia, nombre FROM `{$table}` 
		WHERE departamento = %s AND distrito = '00'
		ORDER BY provincia ASC",
		$departamento
	) );
	$provincias = array();
	foreach ( $results as $row ) {
		$provincias[ $row->provincia ] = $row->nombre;
	}
	return $provincias;
}

/**
 * Obtiene los distritos de una provincia
 * @param string $departamento Código de departamento
 * @param string $provincia Código de provincia
 * @return array Array de distritos
 */
function wpcfact_get_distritos( $departamento, $provincia ) {
	global $wpdb;
	$table = $wpdb->prefix . 'ubigeos';
	$results = $wpdb->get_results( $wpdb->prepare(
		"SELECT DISTINCT distrito, nombre FROM `{$table}` 
		WHERE departamento = %s AND provincia = %s AND distrito != '00'
		ORDER BY distrito ASC",
		$departamento,
		$provincia
	) );
	$distritos = array();
	foreach ( $results as $row ) {
		$distritos[ $row->distrito ] = $row->nombre;
	}
	return $distritos;
}

/**
 * Obtiene el nombre de una ubicación (departamento, provincia o distrito)
 * @param string $departamento Código de departamento
 * @param string $provincia Código de provincia (opcional)
 * @param string $distrito Código de distrito (opcional)
 * @return string Nombre de la ubicación
 */
function wpcfact_get_ubicacion_nombre( $departamento, $provincia = '00', $distrito = '00' ) {
	global $wpdb;
	$table = $wpdb->prefix . 'ubigeos';
	
	// Sanitizar inputs
	$departamento = str_pad( $departamento, 2, '0', STR_PAD_LEFT );
	$provincia = str_pad( $provincia, 2, '0', STR_PAD_LEFT );
	$distrito = str_pad( $distrito, 2, '0', STR_PAD_LEFT );
	
	// Buscar registro exacto
	$result = $wpdb->get_row( $wpdb->prepare(
		"SELECT nombre FROM `{$table}` 
		WHERE departamento = %s AND provincia = %s AND distrito = %s
		LIMIT 1",
		$departamento,
		$provincia,
		$distrito
	) );
	
	if ( $result && ! empty( $result->nombre ) ) {
		return sanitize_text_field( $result->nombre );
	}
	
	// Si es distrito (ZZ != 00), intentar obtener provincia
	if ( $distrito !== '00' ) {
		$result = $wpdb->get_row( $wpdb->prepare(
			"SELECT nombre FROM `{$table}` 
			WHERE departamento = %s AND provincia = %s AND distrito = '00'
			LIMIT 1",
			$departamento,
			$provincia
		) );
		if ( $result && ! empty( $result->nombre ) ) {
			return sanitize_text_field( $result->nombre );
		}
	}
	
	// Si es provincia (YY != 00), intentar obtener departamento
	if ( $provincia !== '00' ) {
		$result = $wpdb->get_row( $wpdb->prepare(
			"SELECT nombre FROM `{$table}` 
			WHERE departamento = %s AND provincia = '00' AND distrito = '00'
			LIMIT 1",
			$departamento
		) );
		if ( $result && ! empty( $result->nombre ) ) {
			return sanitize_text_field( $result->nombre );
		}
	}
	
	// Log de error para debugging
	error_log( "ubigeos.php: No se encontró ubicación para {$departamento}-{$provincia}-{$distrito}" );
	
	return '';
}

